"""Generate the opengl32.dll proxy export list from the real 32-bit opengl32.dll.

Writes src/proxy/opengl32.def and src/proxy/exports.inc. Three kinds of export:
  - HOOKED: implemented in C++ (gl_hooks.cpp / gl_record_hooks.cpp) - camera overrides and the frame recorder
    used for synchronized stereo;
  - BENIGN: forwarded through a plain jump stub - queries, uploads and setup that a second-eye replay can skip;
  - everything else: forwarded through a *counting* stub. Any call to one of those during a frame marks the frame
    as not replayable, so synchronized stereo falls back instead of replaying an incomplete command stream.

Usage: python -I tools/gen_exports.py [path\\to\\SysWOW64\\opengl32.dll]
"""
import struct
import sys
from pathlib import Path

HOOKED = {
    "wglGetProcAddress", "wglSwapBuffers",
    # draws (camera logic + recording)
    "glDrawArrays", "glDrawElements",
    # recorded GL 1.1 state (see docs/FINDINGS.md, gameplay-frame function census)
    "glBindTexture", "glBlendFunc", "glClear", "glClearColor", "glClearDepth", "glClearStencil", "glColorMask",
    "glCullFace", "glDepthFunc", "glDepthMask", "glDepthRange", "glDisable", "glEnable", "glDrawBuffer",
    "glReadBuffer", "glFrontFace", "glLineWidth", "glPointSize", "glPolygonMode", "glPolygonOffset", "glScissor",
    "glViewport", "glStencilFunc", "glStencilMask", "glStencilOp", "glTexParameterf", "glTexParameteri",
    "glTexParameterfv", "glTexParameteriv", "glHint", "glCopyTexSubImage2D", "glDeleteTextures",
}

BENIGN = {
    "glFlush", "glFinish", "glGetError", "glGetString", "glIsEnabled", "glIsTexture", "glIsList",
    "glGetBooleanv", "glGetDoublev", "glGetFloatv", "glGetIntegerv", "glGetPointerv",
    "glGetTexImage", "glGetTexLevelParameterfv", "glGetTexLevelParameteriv", "glGetTexParameterfv",
    "glGetTexParameteriv", "glGetTexEnvfv", "glGetTexEnviv", "glReadPixels", "glPixelStoref", "glPixelStorei",
    "glGenTextures", "glPrioritizeTextures", "glAreTexturesResident",
    "glTexImage1D", "glTexImage2D", "glTexSubImage1D", "glTexSubImage2D",
}


def is_benign(name):
    return name in BENIGN or name.startswith("wgl") or name.startswith("Glmf")


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DLL = Path(r"C:\Windows\SysWOW64\opengl32.dll")


def pe_export_names(path):
    data = path.read_bytes()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: not a PE file")
    machine, nsec = struct.unpack_from("<HH", data, pe + 4)
    if machine != 0x14C:
        raise SystemExit(f"{path}: machine {machine:#x}, expected x86 (0x14c) - use the SysWOW64 copy")
    opt = pe + 24
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    export_rva = struct.unpack_from("<I", data, opt + 96)[0]  # PE32 data directory 0
    sections = [struct.unpack_from("<8sIIII", data, opt + opt_size + i * 40) for i in range(nsec)]

    def off(rva):
        for _, vsize, va, rawsize, rawptr in sections:
            if va <= rva < va + max(vsize, rawsize):
                return rva - va + rawptr
        raise ValueError(f"rva {rva:#x} not in any section")

    e = off(export_rva)
    # IMAGE_EXPORT_DIRECTORY: NumberOfNames at +24, AddressOfNames at +32
    n_names = struct.unpack_from("<I", data, e + 24)[0]
    names_rva = struct.unpack_from("<I", data, e + 32)[0]
    names = []
    for i in range(n_names):
        name_off = off(struct.unpack_from("<I", data, off(names_rva) + 4 * i)[0])
        names.append(data[name_off:data.index(b"\0", name_off)].decode("ascii"))
    return names


def main():
    dll = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DLL
    names = pe_export_names(dll)
    missing = HOOKED - set(names)
    if missing:
        raise SystemExit(f"hooked exports not found in {dll}: {sorted(missing)}")
    forwarded = [n for n in names if n not in HOOKED]

    out = ROOT / "src" / "proxy"
    header = f"; Generated by tools/gen_exports.py from {dll.name} ({len(names)} exports). Do not edit.\n"
    with open(out / "opengl32.def", "w", newline="\n") as f:
        f.write(header + "LIBRARY opengl32\nEXPORTS\n")
        for n in names:
            f.write(f"    {n} = {'hook_' if n in HOOKED else 'stub_'}{n}\n")
    counted = 0
    with open(out / "exports.inc", "w", newline="\n") as f:
        f.write(f"// Generated by tools/gen_exports.py from {dll.name}. Do not edit.\n")
        f.write("// HW2VR_FORWARD(index, name): plain jump to the real export (benign for a second-eye replay).\n")
        f.write("// HW2VR_COUNTED(index, name): counts the call (marks the frame not replayable), then jumps.\n")
        for i, n in enumerate(forwarded):
            kind = "HW2VR_FORWARD" if is_benign(n) else "HW2VR_COUNTED"
            counted += kind == "HW2VR_COUNTED"
            f.write(f"{kind}({i}, {n})\n")
    print(f"{len(names)} exports: {len(HOOKED)} hooked, {len(forwarded) - counted} benign stubs, "
          f"{counted} counting stubs -> {out}")


if __name__ == "__main__":
    main()
